void clearNumberOnClock(int num) {
    // Validate input parameter range
    if (num < 0 || num > 11) {
        return; // Ignore invalid values outside range [0, 11]
    }

    // Array mapping clock indices (0..11) to STM32 GPIO Pin definitions (PA4..PA15)
    uint16_t clock_pins[12] = {
        GPIO_PIN_4,  // 0: 12 o'clock position
        GPIO_PIN_5,  // 1: 1 o'clock position
        GPIO_PIN_6,  // 2: 2 o'clock position
        GPIO_PIN_7,  // 3: 3 o'clock position
        GPIO_PIN_8,  // 4: 4 o'clock position
        GPIO_PIN_9,  // 5: 5 o'clock position
        GPIO_PIN_10, // 6: 6 o'clock position
        GPIO_PIN_11, // 7: 7 o'clock position
        GPIO_PIN_12, // 8: 8 o'clock position
        GPIO_PIN_13, // 9: 9 o'clock position
        GPIO_PIN_14, // 10: 10 o'clock position
        GPIO_PIN_15  // 11: 11 o'clock position
    };

    // Drive GPIO pin HIGH to turn OFF the LED (Active-Low hardware setup)
    // Note: Change to GPIO_PIN_RESET if your hardware configuration is Active-High
    HAL_GPIO_WritePin(GPIOA, clock_pins[num], GPIO_PIN_SET);
}

